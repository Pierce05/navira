'use client';
import Link from 'next/link';
import { useMemo, useState } from 'react';
import { Badge, Card, Empty } from '@/components/ui';
import { buildTimeline, STAGES, type Stage } from '@/lib/brief/timeline';
import { evaluateRules } from '@/lib/rules/engine';
import { computeMissing } from '@/lib/rules/missing';
import { useStore } from '@/lib/store';
import { useT } from '@/lib/useT';
import { describe } from '@/lib/extract/describe';

const STAGE_TITLE: Record<Stage, string> = { onset: 'Onset', pattern: 'Pattern', frequency: 'Frequency', severity: 'Severity', impact: 'Impact on daily life' };

export function TimelineView() {
  const t = useT();
  const { story, hydrated } = useStore();
  const [filter, setFilter] = useState('all');
  const facts = story?.facts ?? [];
  const entries = useMemo(() => buildTimeline(facts), [facts]);
  const results = useMemo(() => evaluateRules(facts).filter((r) => r.fired), [facts]);
  const missing = useMemo(() => computeMissing(facts), [facts]);
  if (!hydrated) return <p role="status" className="text-muted">Loading…</p>;
  if (!story) return <Empty text={t('emptyStory')} />;

  const symptoms = [...new Map(entries.map((e) => [e.symptomKey, e.symptom])).entries()];
  const shown = symptoms.filter(([k]) => filter === 'all' || k === filter);

  return (
    <div className="grid gap-6">
      {entries.length === 0 ? <Empty text="No confirmed symptoms yet. Confirm what we picked up on the review screen and it will show here." /> : (
        <>
          <div className="flex flex-wrap items-center gap-3">
            <label htmlFor="flt" className="text-sm text-muted">Show</label>
            <select id="flt" value={filter} onChange={(e) => setFilter(e.target.value)} className="min-h-[44px] rounded-full border border-line bg-surface px-3 text-ink">
              <option value="all">All symptoms</option>{symptoms.map(([k, n]) => <option key={k} value={k}>{n}</option>)}
            </select>
            <Badge tone="patient"><span aria-hidden="true">●</span>{t('provPatient')}</Badge>
            {story.synthetic ? <Badge tone="warn">{t('synthetic')}</Badge> : null}
          </div>
          {shown.map(([key, name]) => (
            <Card key={key}>
              <h2 className="mb-4 text-2xl first-letter:uppercase">{name}</h2>
              <ol className="relative ml-3 border-l-2 pl-6" style={{ borderColor: 'var(--accent)' }}>
                {STAGES.map((s) => {
                  const e = entries.find((x) => x.symptomKey === key && x.stage === s)!;
                  return (
                    <li key={s} className="relative pb-5 last:pb-0">
                      <span aria-hidden="true" className={`absolute -left-[33px] top-1.5 h-3.5 w-3.5 rounded-full border-2 ${e.unknown ? 'border-line bg-bg' : 'border-accent-strong bg-accent-strong'}`} />
                      <p className="text-sm text-muted">{STAGE_TITLE[s]}</p>
                      <p className={e.unknown ? 'italic text-muted' : 'text-lg'}>{e.text}{e.approx && !e.unknown ? <span className="ml-2 text-sm text-muted">(approx.)</span> : null}</p>
                    </li>
                  );
                })}
              </ol>
            </Card>
          ))}
        </>
      )}

      <Card>
        <h2 className="text-2xl">Features commonly considered in evaluation</h2>
        <p className="mt-1 text-sm text-muted">Generated by Navira from what you confirmed. Not a diagnosis. Each one shows why it appeared.</p>
        {results.length === 0 ? <p className="mt-3 text-muted">Nothing reviewed has come up yet.</p> : (
          <ul className="mt-4 grid gap-3">
            {results.map((r) => (
              <li key={r.ruleId} className="rounded-2xl border border-dashed border-accent-strong p-4">
                <div className="flex flex-wrap items-center gap-2"><Badge tone="system"><span aria-hidden="true">◇</span>{t('provSystem')}</Badge><span className="text-sm text-muted">{r.ruleId}</span></div>
                <p className="mt-2 text-lg">{r.patientText}</p>
                <details className="mt-1 text-sm">
                  <summary className="min-h-[44px] cursor-pointer py-2 text-accent-strong">Why this appeared</summary>
                  <p>Because you confirmed: {r.reasonFactIds.map((id) => facts.find((f) => f.id === id)).filter(Boolean).map((f) => describe(f!)).join('; ')}.</p>
                  <p className="mt-1 text-muted">Source: {r.source.name}{r.source.section ? `, ${r.source.section}` : ''}</p>
                </details>
              </li>
            ))}
          </ul>
        )}
      </Card>

      <Card>
        <h2 className="text-2xl">{t('notYetKnown')}</h2>
        <p className="mt-1 text-sm text-muted">Things a clinician may want to ask about. These are gaps, not findings.</p>
        {missing.length === 0 ? <p className="mt-3 text-muted">Nothing flagged right now.</p> : (
          <ul className="mt-3 list-disc space-y-1 pl-6">{missing.map((m) => <li key={m.key}>{m.label}{m.unsure ? <span className="text-muted"> (you were not sure)</span> : null}</li>)}</ul>
        )}
      </Card>

      <div className="flex flex-wrap gap-3">
        <Link href="/followups/" className="inline-flex min-h-[44px] items-center rounded-full border border-line px-5">More questions</Link>
        <Link href="/brief/" className="inline-flex min-h-[44px] items-center rounded-full bg-accent-strong px-6 font-medium text-on-accent">Make my brief</Link>
      </div>
    </div>
  );
}
