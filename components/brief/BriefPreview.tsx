import type { BriefModel } from '@/lib/brief/model';

const Sec = ({ title, tag, system, children }: { title: string; tag: string; system?: boolean; children: React.ReactNode }) => (
  <section className="mt-4 first:mt-0">
    <div className="flex items-baseline justify-between gap-3 border-b border-line pb-0.5">
      <h3 className="font-sans text-[15px] font-bold">{title}</h3>
      <span className="text-xs text-muted"><span aria-hidden="true">{system ? '◇ ' : '● '}</span>{tag}</span>
    </div>
    <div className="mt-1 text-[14px] leading-snug">{children}</div>
  </section>
);
const List = ({ items, empty }: { items: string[]; empty: string }) => items.length ? <ul className="list-disc pl-5">{items.map((t, i) => <li key={i}>{t}</li>)}</ul> : <p>{empty}</p>;

/** HTML preview of exactly the same model that the PDF renders. */
export function BriefPreview({ m }: { m: BriefModel }) {
  return (
    <article id="brief-print" aria-label="Brief preview" className="mx-auto w-full max-w-[794px] rounded-2xl border border-line bg-surface p-6 text-ink sm:p-9">
      <h2 className="font-display text-2xl font-semibold">{m.title}</h2>
      <p className="text-sm text-muted">Generated {m.generatedOn}{m.initials ? `, initials: ${m.initials}` : ''}</p>
      <p className="mt-2 rounded border border-ink px-2 py-0.5 text-sm font-bold">{m.disclaimer}</p>
      {m.synthetic ? <p className="mt-1 text-sm font-bold underline">SYNTHETIC DEMO DATA: not a real patient.</p> : null}

      <Sec title="In my words" tag="Reported by the patient"><p className="deva">{m.excerpt ? `“${m.excerpt}”` : 'No excerpt chosen.'}</p></Sec>
      <Sec title="Timeline" tag="Reported by the patient"><p>{m.timelineLine}</p></Sec>
      <Sec title="Symptoms" tag="Reported by the patient">
        <div className="overflow-x-auto">
          <table className="w-full min-w-[30rem] text-left text-[14px]">
            <thead><tr className="border-b border-line"><th className="pr-2 font-bold">Symptom</th><th className="pr-2 font-bold">Severity</th><th className="pr-2 font-bold">Cycle relation</th><th className="pr-2 font-bold">Since</th><th className="font-bold">Confirmed</th></tr></thead>
            <tbody>{m.symptoms.length ? m.symptoms.map((r, i) => (
              <tr key={i} className="border-b" style={{ borderColor: 'var(--soft-line)' }}><td className="pr-2 first-letter:uppercase">{r.name}</td><td className="pr-2">{r.severity}</td><td className="pr-2">{r.cycle}</td><td className="pr-2">{r.since}</td><td>{r.confirmed}</td></tr>
            )) : <tr><td colSpan={5} className="py-1">No symptoms confirmed yet.</td></tr>}</tbody>
          </table>
        </div>
      </Sec>
      <Sec title="Impact on daily life" tag="Reported by the patient"><List items={m.impact} empty="Not stated." /></Sec>
      <Sec title="What I have tried" tag="Reported by the patient"><List items={m.tried} empty="Not stated." /></Sec>
      {m.showHistory ? <Sec title="Relevant history" tag="Reported by the patient"><List items={m.history} empty="Not stated." /></Sec> : null}
      <Sec title="Features commonly considered in evaluation" tag="Generated by Navira from confirmed answers. Not a diagnosis." system>
        {m.features.length ? <ul className="list-disc pl-5">{m.features.map((f) => <li key={f.id}>{f.text} <span className="text-muted">[{f.id}; {f.source}]</span></li>)}</ul> : <p>None of the reviewed features were reported.</p>}
      </Sec>
      <Sec title="Not yet known" tag="Generated by Navira. Gaps, not findings." system><List items={m.notKnown} empty="Nothing flagged." /></Sec>
      <Sec title="Questions I would like to discuss" tag="Reported by the patient"><ol className="list-decimal pl-5">{m.questions.map((q, i) => <li key={i}>{q}</li>)}</ol></Sec>
      {m.notes ? <Sec title="My notes" tag="Reported by the patient"><p>{m.notes}</p></Sec> : null}
      {m.safetyNote ? <p className="mt-3 text-sm font-bold">{m.safetyNote}</p> : null}
      <footer className="mt-4 border-t border-line pt-2 text-xs text-muted">
        <p>Sources: {m.sources.length ? m.sources.join('; ') : 'none cited'}. Rules {m.rulesVersion}.</p>
        {m.draftNotice ? <p>{m.draftNotice}</p> : null}
        <p>Patient-confirmed on {m.confirmedOn}. Navira helps prepare for a conversation with a clinician. It does not diagnose.</p>
      </footer>
    </article>
  );
}
