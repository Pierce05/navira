/* Single A4 page, B&W-safe, selectable text, body >= 10 pt. Section order follows PRD section 9. */
import React from 'react';
import { Document, Page, StyleSheet, Text, View, type DocumentProps } from '@react-pdf/renderer';
import type { BriefModel } from './model';

const INK = '#111111', MID = '#444444', RULE = '#777777';
const s = StyleSheet.create({
  page: { paddingTop: 22, paddingBottom: 22, paddingHorizontal: 30, fontFamily: 'DM Sans', fontSize: 10, color: INK, lineHeight: 1.22 },
  h1: { fontFamily: 'Fraunces', fontWeight: 600, fontSize: 16, marginBottom: 1 },
  meta: { fontSize: 10, color: MID },
  banner: { borderWidth: 1, borderColor: INK, paddingVertical: 2, paddingHorizontal: 5, marginTop: 3, fontWeight: 700 },
  synth: { marginTop: 3, fontWeight: 700, fontSize: 10, textDecoration: 'underline' },
  sec: { marginTop: 4 },
  head: { flexDirection: 'row', justifyContent: 'space-between', borderBottomWidth: 0.8, borderBottomColor: RULE, marginBottom: 2, paddingBottom: 0.5 },
  title: { fontWeight: 700, fontSize: 10.5 },
  tag: { fontSize: 8, color: MID, fontStyle: 'normal' },
  row: { flexDirection: 'row', borderBottomWidth: 0.4, borderBottomColor: '#bbbbbb', paddingVertical: 1 },
  th: { fontWeight: 700 },
  c1: { width: '29%' }, c2: { width: '12%' }, c3: { width: '20%' }, c4: { width: '25%' }, c5: { width: '14%' },
  li: { marginLeft: 8 },
  foot: { marginTop: 5, borderTopWidth: 0.8, borderTopColor: RULE, paddingTop: 2, fontSize: 8, color: MID, lineHeight: 1.2 },
});

const Section = ({ title, tag, children }: { title: string; tag: string; children: React.ReactNode }) => (
  <View style={s.sec} wrap={false}>
    <View style={s.head}><Text style={s.title}>{title}</Text><Text style={s.tag}>{tag}</Text></View>
    {children}
  </View>
);
const Lines = ({ items, empty }: { items: string[]; empty: string }) =>
  items.length ? <>{items.map((t, i) => <Text key={i} style={s.li}>- {t}</Text>)}</> : <Text style={s.li}>{empty}</Text>;

const PATIENT = 'Reported by the patient';
const SYSTEM = 'Generated by Navira from confirmed answers. Not a diagnosis.';
const hasDeva = (t: string) => /[\u0900-\u097F]/.test(t);

export function BriefDocument({ m }: { m: BriefModel }) {
  return (
    <Document title={m.title} author="Navira (patient-prepared)" subject="Patient-reported symptom summary">
      <Page size="A4" style={s.page}>
        <View>
          <Text style={s.h1}>{m.title}</Text>
          <Text style={s.meta}>Generated {m.generatedOn}{m.initials ? `  ·  Initials: ${m.initials}` : ''}</Text>
          <Text style={s.banner}>{m.disclaimer}</Text>
          {m.synthetic ? <Text style={s.synth}>SYNTHETIC DEMO DATA: not a real patient.</Text> : null}
        </View>

        <Section title="In my words" tag={PATIENT}>
          <Text style={hasDeva(m.excerpt) ? { fontFamily: 'Noto Sans Devanagari' } : undefined}>{m.excerpt ? `"${m.excerpt}"` : 'No excerpt chosen.'}</Text>
        </Section>

        <Section title="Timeline" tag={PATIENT}><Text>{m.timelineLine}</Text></Section>

        <Section title="Symptoms" tag={PATIENT}>
          <View style={s.row}>
            <Text style={[s.c1, s.th]}>Symptom</Text><Text style={[s.c2, s.th]}>Severity</Text><Text style={[s.c3, s.th]}>Cycle relation</Text>
            <Text style={[s.c4, s.th]}>Since</Text><Text style={[s.c5, s.th]}>Confirmed</Text>
          </View>
          {m.symptoms.length ? m.symptoms.map((r, i) => (
            <View key={i} style={s.row}>
              <Text style={s.c1}>{r.name}</Text><Text style={s.c2}>{r.severity}</Text><Text style={s.c3}>{r.cycle}</Text>
              <Text style={s.c4}>{r.since}</Text><Text style={s.c5}>{r.confirmed}</Text>
            </View>
          )) : <Text style={s.li}>No symptoms confirmed yet.</Text>}
        </Section>

        <Section title="Impact on daily life" tag={PATIENT}><Lines items={m.impact} empty="Not stated." /></Section>
        <Section title="What I have tried" tag={PATIENT}><Lines items={m.tried} empty="Not stated." /></Section>
        {m.showHistory ? <Section title="Relevant history" tag={PATIENT}><Lines items={m.history} empty="Not stated." /></Section> : null}

        <Section title="Features commonly considered in evaluation" tag={SYSTEM}>
          {m.features.length ? m.features.map((f) => (
            <Text key={f.id} style={s.li}>- {f.text} [{f.id}; {f.source}]</Text>
          )) : <Text style={s.li}>None of the reviewed features were reported.</Text>}
        </Section>

        <Section title="Not yet known" tag={SYSTEM}><Lines items={m.notKnown} empty="Nothing flagged." /></Section>

        <Section title="Questions I would like to discuss" tag={PATIENT}>
          {m.questions.map((q, i) => <Text key={i} style={s.li}>{i + 1}. {q}</Text>)}
        </Section>

        {m.notes ? <Section title="My notes" tag={PATIENT}><Text>{m.notes.slice(0, 240)}</Text></Section> : null}
        {m.safetyNote ? <Text style={[s.sec, { fontWeight: 700 }]}>{m.safetyNote}</Text> : null}

        <View style={s.foot}>
          <Text>Sources: {m.sources.length ? m.sources.join('; ') : 'none cited'}. Rules {m.rulesVersion}.</Text>
          {m.draftNotice ? <Text>{m.draftNotice}</Text> : null}
          <Text>Patient-confirmed on {m.confirmedOn}. Navira helps prepare for a conversation with a clinician. It does not diagnose.</Text>
        </View>
      </Page>
    </Document>
  );
}

/** Root element for pdf() / renderToBuffer(): react-pdf wants the <Document> itself at the top. */
export function briefElement(m: BriefModel) {
  return BriefDocument({ m }) as React.ReactElement<DocumentProps>;
}
